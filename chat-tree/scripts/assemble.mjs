// Wrap chat-tree/src/chat-tree.js into a single disk plugin.js that only imports
// @hermes/plugin-sdk, react, and react/jsx-runtime.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = readFileSync(join(root, 'src/chat-tree.js'), 'utf8')

if (/^import /m.test(src)) throw new Error('chat-tree.js must have no imports')
const body = src.replace(/^export (function|const) /gm, '$1 ')
if (/^export /m.test(body)) throw new Error('unhandled export left in chat-tree.js')

const preamble = `/* chat-tree — Hermes Desktop plugin
 *
 * Assembled from chat-tree/src/chat-tree.js. Do not edit this file by hand; run
 * \`npm run assemble:chat-tree\`. Imports only @hermes/plugin-sdk, react and
 * react/jsx-runtime, as the disk-plugin loader requires.
 */
import * as sdk from '@hermes/plugin-sdk'
import { jsx, jsxs } from 'react/jsx-runtime'

const host = sdk.host
const atom = sdk.atom
const useValue = sdk.useValue
const Button = sdk.Button || 'button'
const Input = sdk.Input || 'input'
const ScrollArea = sdk.ScrollArea || 'div'
// Hermes's model picker for the Branch form; undefined on an SDK without it (the form then says so).
const ModelCatalogMenu = sdk.ModelCatalogMenu
const ModelMenuCloseContext = sdk.ModelMenuCloseContext
const DropdownMenu = sdk.DropdownMenu
const DropdownMenuTrigger = sdk.DropdownMenuTrigger
const DropdownMenuContent = sdk.DropdownMenuContent
const reasoningEffortLabel = sdk.reasoningEffortLabel
const BranchIcon = sdk.icons?.GitForkIcon || sdk.icons?.GitFork
// Row and header icons, tooltips and the merge popover; each is undefined on an SDK without it
// (the pane then draws the icon, uses the native title, or shows the pick under the graph).
const TabIcon = sdk.icons?.ExternalLink
const RefreshIcon = sdk.icons?.RefreshCwIcon || sdk.icons?.RefreshCw
const Codicon = sdk.Codicon
const Tip = sdk.Tip
const Popover = sdk.Popover
const PopoverTrigger = sdk.PopoverTrigger
const PopoverContent = sdk.PopoverContent

`

const outro = `
const _plugin = createChatTree({
  host,
  jsx,
  jsxs,
  atom,
  useValue,
  Button,
  Input,
  ScrollArea,
  ModelCatalogMenu,
  ModelMenuCloseContext,
  DropdownMenu,
  DropdownMenuTrigger,
  DropdownMenuContent,
  reasoningEffortLabel,
  BranchIcon,
  TabIcon,
  RefreshIcon,
  Codicon,
  Tip,
  Popover,
  PopoverTrigger,
  PopoverContent,
  setTimeout: (fn, ms) => globalThis.setTimeout(fn, ms),
  clearTimeout: (id) => globalThis.clearTimeout(id),
})

export default {
  id: 'chat-tree',
  name: 'Chat Tree',
  register(ctx) {
    _plugin.register(ctx)
  },
}
`

const outDir = join(root, 'desktop')
mkdirSync(outDir, { recursive: true })
const dest = join(outDir, 'plugin.js')
writeFileSync(dest, `${preamble}${body.trim()}\n${outro}`)
const source = readFileSync(dest, 'utf8')
const imports = [...source.matchAll(/^import .+$/gm)].map((m) => m[0])
if (imports.length !== 2) throw new Error(`unexpected imports: ${imports.join(' | ')}`)
console.log(`wrote ${dest} (${source.split('\n').length} lines)`)
