// Concatenate src/*.js into a single disk plugin.js that only imports
// @hermes/plugin-sdk, react, and react/jsx-runtime.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const files = [
  'src/providers.js',
  'src/inline-provider.js',
  'src/session-glossary.js',
  'src/static-glossary.js',
  'src/wiki-provider.js',
  'src/mdn-provider.js',
  'src/coined-provider.js',
  'src/llm-provider.js',
  'src/termline.js',
  'src/plugin-factory.js',
]

const BINDING = /^(export )?(function|const|let|var) (\w+)/gm

function slug(path) {
  return path.replace(/^src\//, '').replace(/\.js$/, '').replace(/[^a-z0-9]+/gi, '_')
}

function stripAndScope(src, path, used) {
  const suffix = slug(path)
  // Capture exported vs local names before stripping export keywords.
  const names = []
  let m
  const re = new RegExp(BINDING.source, 'gm')
  while ((m = re.exec(src)) !== null) names.push({ exported: Boolean(m[1]), name: m[3] })

  let s = src.replace(/^import\s+[\s\S]*?from\s+['"][^'"]+['"];?\n/gm, '')
  for (const { exported, name } of names) {
    if (exported) {
      if (used.has(name)) throw new Error(`exported name collision: ${name} in ${path}`)
      used.add(name)
      continue
    }
    if (used.has(name)) {
      const next = `${name}_${suffix}`
      if (used.has(next)) throw new Error(`could not rename ${name} in ${path}`)
      s = s.replace(new RegExp(`\\b${name}\\b`, 'g'), next)
      used.add(next)
    } else {
      used.add(name)
    }
  }
  s = s.replace(/^export function /gm, 'function ')
  s = s.replace(/^export const /gm, 'const ')
  s = s.replace(/^export \{[^}]+\} ;?\n/gm, '')
  if (/^import /m.test(s) || /^export /m.test(s)) {
    throw new Error(`unhandled import/export left in ${path}`)
  }
  return `// ---- ${path} ----\n${s.trim()}\n`
}

const preamble = `/* concept-links — Hermes Desktop plugin
 *
 * Assembled from src/*.js. Do not edit this file by hand; run
 * \`npm run assemble\`. Imports only @hermes/plugin-sdk, react and
 * react/jsx-runtime, as the disk-plugin loader requires.
 */
import * as sdk from '@hermes/plugin-sdk'
import { jsx, jsxs } from 'react/jsx-runtime'

const host = sdk.host
const atom = sdk.atom
const useValue = sdk.useValue
const Tip = sdk.Tip
const Button = sdk.Button || 'button'
const ScrollArea = sdk.ScrollArea || 'div'
const EmptyState = sdk.EmptyState || 'div'
const Badge = sdk.Badge || 'span'
const Switch = sdk.Switch || 'button'
const Separator = sdk.Separator || 'hr'

`

const outro = `
const _plugin = createPlugin({
  host,
  jsx,
  jsxs,
  atom,
  useValue,
  Tip,
  Button,
  ScrollArea,
  EmptyState,
  Badge,
  Switch,
  Separator,
})

export default {
  id: 'concept-links',
  name: 'Concept Links',
  register(ctx) {
    _plugin.register(ctx)
  },
}
`

const used = new Set(['host', 'atom', 'useValue', 'Tip', 'Button', 'ScrollArea', 'EmptyState', 'Badge', 'Switch', 'Separator', 'sdk', 'jsx', 'jsxs', '_plugin'])
const body = files.map((rel) => stripAndScope(readFileSync(join(root, rel), 'utf8'), rel, used)).join('\n')
const outDir = join(root, 'desktop')
mkdirSync(outDir, { recursive: true })
const dest = join(outDir, 'plugin.js')
writeFileSync(dest, preamble + body + outro)
const source = readFileSync(dest, 'utf8')
const lines = source.split('\n').length
const imports = [...source.matchAll(/^import .+$/gm)].map((m) => m[0])
if (imports.length !== 2) throw new Error(`unexpected imports: ${imports.join(' | ')}`)
console.log(`wrote ${dest} (${lines} lines)`)
